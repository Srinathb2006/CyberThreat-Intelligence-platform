CREATE TABLE yara_scans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 apk_analysis_id BIGINT NOT NULL UNIQUE REFERENCES apk_analyses(id),
 mode VARCHAR(16) NOT NULL,
 status VARCHAR(32) NOT NULL,
 message VARCHAR(500) NOT NULL,
 scanned_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE yara_matches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 yara_scan_id BIGINT NOT NULL REFERENCES yara_scans(id) ON DELETE CASCADE,
 rule_name VARCHAR(255) NOT NULL,
 severity VARCHAR(16) NOT NULL,
 description VARCHAR(1000) NOT NULL,
 evidence VARCHAR(1000) NOT NULL
);
CREATE INDEX idx_yara_matches_scan ON yara_matches(yara_scan_id);
