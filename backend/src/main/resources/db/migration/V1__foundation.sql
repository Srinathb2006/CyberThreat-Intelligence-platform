CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, password VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','ANALYST','USER')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE scans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scan_type VARCHAR(20) NOT NULL CHECK (scan_type IN ('APK','URL','PHISHING')),
 target VARCHAR(2048) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED')),
 risk_score INTEGER CHECK (risk_score BETWEEN 0 AND 100),
 risk_level VARCHAR(20) NOT NULL CHECK (risk_level IN ('UNKNOWN','LOW','MEDIUM','HIGH','CRITICAL')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, completed_at TIMESTAMP WITH TIME ZONE,
 user_id BIGINT NOT NULL REFERENCES app_users(id)
);
CREATE INDEX idx_scans_user_created ON scans(user_id,created_at);
CREATE TABLE alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(200) NOT NULL,
 description VARCHAR(4000) NOT NULL, severity VARCHAR(20) NOT NULL CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
 status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN','ACKNOWLEDGED','RESOLVED')),
 source VARCHAR(255) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 scan_id BIGINT REFERENCES scans(id)
);
CREATE INDEX idx_alerts_scan ON alerts(scan_id);

